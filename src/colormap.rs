//! Colormaps (value `t` in 0..=1 -> RGB).

pub const NAMES: [&str; 6] =
    ["Rainbow (GiD)", "Viridis", "Turbo", "Coolwarm", "Plasma", "Grayscale"];

fn lerp_table(pts: &[(f32, [f32; 3])], t: f32) -> [f32; 3] {
    let t = t.clamp(0.0, 1.0);
    for w in pts.windows(2) {
        let (t0, c0) = w[0];
        let (t1, c1) = w[1];
        if t <= t1 {
            let f = if t1 > t0 { (t - t0) / (t1 - t0) } else { 0.0 };
            return [
                c0[0] + (c1[0] - c0[0]) * f,
                c0[1] + (c1[1] - c0[1]) * f,
                c0[2] + (c1[2] - c0[2]) * f,
            ];
        }
    }
    pts.last().unwrap().1
}

fn evenly(table: &[[f32; 3]], t: f32) -> [f32; 3] {
    let n = table.len() - 1;
    let pts: Vec<(f32, [f32; 3])> = table
        .iter()
        .enumerate()
        .map(|(i, c)| (i as f32 / n as f32, [c[0] / 255.0, c[1] / 255.0, c[2] / 255.0]))
        .collect();
    lerp_table(&pts, t)
}

/// RGB in 0..=1.
pub fn sample(name: &str, t: f32) -> [f32; 3] {
    let t = t.clamp(0.0, 1.0);
    match name {
        "Viridis" => evenly(
            &[
                [68., 1., 84.],
                [71., 44., 122.],
                [59., 81., 139.],
                [44., 113., 142.],
                [33., 144., 141.],
                [39., 173., 129.],
                [92., 200., 99.],
                [170., 220., 50.],
                [253., 231., 37.],
            ],
            t,
        ),
        "Plasma" => evenly(
            &[
                [13., 8., 135.],
                [84., 2., 163.],
                [139., 10., 165.],
                [185., 50., 137.],
                [219., 92., 104.],
                [244., 136., 73.],
                [254., 188., 43.],
                [240., 249., 33.],
            ],
            t,
        ),
        "Turbo" => {
            let p = |c: [f32; 6]| {
                let mut r = 0.0;
                for k in (0..6).rev() {
                    r = r * t + c[k];
                }
                r.clamp(0.0, 1.0)
            };
            [
                p([0.13572138, 4.615_392_7, -42.660_323, 132.131_08, -152.942_4, 59.286_38]),
                p([0.09140261, 2.194_188_4, 4.842_966_5, -14.185_033, 4.277_298_5, 2.829_566]),
                p([0.1066733, 12.641_946, -60.582_05, 110.362_77, -89.903_11, 27.348_25]),
            ]
        }
        "Coolwarm" => evenly(
            &[
                [59., 76., 192.],
                [141., 176., 254.],
                [221., 221., 221.],
                [244., 154., 123.],
                [180., 4., 38.],
            ],
            t,
        ),
        "Grayscale" => [t, t, t],
        // "Rainbow (GiD)" and anything unknown: matplotlib's "jet".
        _ => {
            let r = lerp_table(
                &[
                    (0.0, [0., 0., 0.]),
                    (0.35, [0., 0., 0.]),
                    (0.66, [1., 1., 1.]),
                    (0.89, [1., 1., 1.]),
                    (1.0, [0.5, 0.5, 0.5]),
                ],
                t,
            )[0];
            let g = lerp_table(
                &[
                    (0.0, [0., 0., 0.]),
                    (0.125, [0., 0., 0.]),
                    (0.375, [1., 1., 1.]),
                    (0.64, [1., 1., 1.]),
                    (0.91, [0., 0., 0.]),
                    (1.0, [0., 0., 0.]),
                ],
                t,
            )[0];
            let b = lerp_table(
                &[
                    (0.0, [0.5, 0.5, 0.5]),
                    (0.11, [1., 1., 1.]),
                    (0.34, [1., 1., 1.]),
                    (0.65, [0., 0., 0.]),
                    (1.0, [0., 0., 0.]),
                ],
                t,
            )[0];
            [r, g, b]
        }
    }
}

pub fn to_u8(c: [f32; 3]) -> [u8; 3] {
    [
        (c[0] * 255.0 + 0.5) as u8,
        (c[1] * 255.0 + 0.5) as u8,
        (c[2] * 255.0 + 0.5) as u8,
    ]
}

pub const LUT_SIZE: usize = 512;

pub fn lut(name: &str) -> Vec<[u8; 4]> {
    (0..LUT_SIZE)
        .map(|i| {
            let c = to_u8(sample(name, i as f32 / (LUT_SIZE - 1) as f32));
            [c[0], c[1], c[2], 255]
        })
        .collect()
}
